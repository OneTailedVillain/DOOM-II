# Reverse mapping for lookup by DS name
DS_TO_STRIFE_VOICE = {v: k for k, v in STRIFE_VOICE_MAPPINGS.items()}

def map_strife_voice_name(voice_name):
    """Map a Strife voice lump name to DSxxxxxx format."""
    return STRIFE_VOICE_MAPPINGS.get(voice_name.upper(), None)

def map_ds_name_to_strife(ds_name):
    """Map a DSxxxxxx name back to original Strife voice name."""
    return DS_TO_STRIFE_VOICE.get(ds_name.upper(), None)

def is_strife_voice_lump(lump_name):
    """Check if a lump name is a Strife voice lump."""
    return lump_name.upper() in STRIFE_VOICE_MAPPINGS